export function chunkSentenceByMeaning(sentence: string): string {
  const words = sentence.trim().split(/\s+/);
  if (words.length <= 4) return sentence.trim();

  const result: string[] = [];
  let wordsSinceLastSlash = 0;

  for (let i = 0; i < words.length; i++) {
    const current = words[i];
    const cleanCurr = current.toLowerCase().replace(/[^a-z]/g, '');
    const prevWord = i > 0 ? words[i - 1] : '';
    const cleanPrev = prevWord.toLowerCase().replace(/[^a-z]/g, '');

    // 이전 단어가 콤마/세미콜론으로 끝났고, 뒤에 최소 2단어가 남아있다면 끊어 읽기
    if (
      i > 0 &&
      /[,;:]$/.test(prevWord) &&
      wordsSinceLastSlash >= 2 &&
      i < words.length - 1
    ) {
      result.push('/');
      wordsSinceLastSlash = 0;
    } else if (
      i >= 2 &&
      i < words.length - 2 &&
      wordsSinceLastSlash >= 3 &&
      CHUNK_BOUNDARY_BEFORE.has(cleanCurr) &&
      !DETERMINERS_AND_AUX.has(cleanPrev)
    ) {
      // 전치사·접속사·관계사 앞에서 의미 단위로 끊기 (단, 앞 단어가 관사/조동사가 아닐 때)
      result.push('/');
      wordsSinceLastSlash = 0;
    }

    result.push(current);
    wordsSinceLastSlash++;
  }

  return result.join(' ');
}

export function analyzeCustomSchoolPassage(rawText: string): CustomPassageAnalysisResult {
  const trimmed = (rawText || '').trim();
  if (!trimmed) {
    return {
      isEmpty: true,
      statusMessage: '⚠️ 분석할 영어 지문을 입력창에 붙여넣어 주세요. (최소 1문장 이상)',
      sentences: [],
    };
  }

  // Safari < 16.4 호환을 위해 후방 탐색(?<=) 없이 문장 단위로 분리
  const rawMatches = trimmed.match(/[^.!?]+[.!?]+|[^.!?]+$/g) || [];
  const validSents = rawMatches
    .map((s) => s.trim())
    .filter((s) => s.split(/\s+/).length >= 4);

  if (validSents.length === 0) {
    return {
      isEmpty: true,
      statusMessage:
        '⚠️ 4단어 이상으로 이루어진 완전한 영어 문장을 입력해 주세요.',
      sentences: [],
    };
  }

  return {
    isEmpty: false,
    statusMessage: `✅ 총 ${validSents.length}개의 문장에서 의미 단위 소리블록·빈칸 추론·어순 배열 문제를 생성했습니다.`,
    sentences: validSents.map((sent, idx) => {
      const words = sent.split(/\s+/);
      const contentWords = words
        .map((w) => w.replace(/[^a-zA-Z-]/g, ''))
        .filter(
          (w) => w.length >= 5 && !STOP_WORDS_SET.has(w.toLowerCase())
        );

      const fallbackWord =
        words
          .map((w) => w.replace(/[^a-zA-Z-]/g, ''))
          .find((w) => w.length >= 4 && !STOP_WORDS_SET.has(w.toLowerCase())) ||
        words[Math.min(1, words.length - 1)].replace(/[^a-zA-Z-]/g, '') ||
        'word';

      const answerWord = contentWords[0] || fallbackWord;
      const safePattern = new RegExp(`\\b${escapeRegExp(answerWord)}\\b`);
      const blankQuizSentence = safePattern.test(sent)
        ? sent.replace(safePattern, '____________')
        : sent.replace(answerWord, '____________');

      return {
        idx: idx + 1,
        rawEn: sent,
        soundBlockEn: chunkSentenceByMeaning(sent),
        extractedKeywords: contentWords.slice(0, 4),
        blankQuizSentence,
        answerWord,
        scrambledWords: deterministicShuffle(words, idx + 101),
      };
    }),
  };
}
