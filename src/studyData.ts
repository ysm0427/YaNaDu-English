export function generateCombinatorialSentences(
  seed: number,
  count: number = 12
): GeneratedSyntaxItem[] {
  const total = VERIFIED_SYNTAX_ARCHIVE.length;
  const safeSeed = Number.isFinite(seed) && seed >= 1 ? Math.floor(seed) : 1;
  const safeCount =
    Number.isFinite(count) && count >= 1
      ? Math.min(Math.floor(count), total)
      : total;
  const offset = ((safeSeed - 1) % total + total) % total;

  return Array.from({ length: safeCount }, (_, i) => {
    const item = VERIFIED_SYNTAX_ARCHIVE[(offset + i) % total];
    const fullTokens = item.sentenceEn.split(/\s+/);
    return {
      id: `verified-syntax-${safeSeed}-${i}`,
      openerRule: item.openerRule,
      sentenceEn: item.sentenceEn,
      ipaLine: item.ipaLine,
      pronLine: item.pronLine,
      sentenceKo: item.sentenceKo,
      paraphrasedEn: item.paraphrasedEn,
      targetWord: item.targetWord,
      matchedForm: item.matchedForm,
      scrambleTokens: deterministicShuffle(fullTokens, safeSeed * 17 + i),
    };
  });
}

