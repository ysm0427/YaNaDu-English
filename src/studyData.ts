// 입력 경계값(0, 음수, NaN)을 안전하게 보정하여 어휘 엔트리를 반환
export function getExpandedWordbookByDay(
  level: WordbookLevel,
  day: number
): WordbookEntry[] {
  const pool =
    level === '중등 필수'
      ? VERIFIED_MID_VOCAB
      : level === '고등·수능 핵심'
      ? VERIFIED_CSAT_VOCAB
      : level === '비즈니스·실무'
      ? VERIFIED_BIZ_VOCAB
      : VERIFIED_OPIC_VOCAB;

  const safeDay =
    Number.isFinite(day) && day >= 1 ? Math.min(100, Math.floor(day)) : 1;
  const offset = (((safeDay - 1) * 5) % pool.length + pool.length) % pool.length;

  return Array.from({ length: pool.length }, (_, idx) => {
    const item = pool[(offset + idx) % pool.length];
    return {
      day: safeDay,
      level,
      word: item.word,
      matchedForm: item.matchedForm,
      ipa: item.ipa,
      pron: item.pron,
      soundBlock: item.soundBlock,
      soundMethod: item.soundMethod,
      meaning: item.meaning,
      pos: item.pos,
      posLabel: `${item.posName} (${item.pos})`,
      comp: item.comp,
      compLabel: `${item.compName} (${item.comp})`,
      collocation: item.collocation,
      collocationKo: item.collocationKo,
      exampleEn: item.exampleEn,
      examplePron: item.examplePron,
      exampleKo: item.exampleKo,
      derivativesTip: item.derivativesTip,
    };
  });
}

