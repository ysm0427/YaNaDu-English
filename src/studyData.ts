export function getExpandedWordbookByDay(
  level: '중등 필수' | '고등·수능 핵심' | '비즈니스·실무' | '오픽(OPIc)·구동사',
  day: number
): WordbookEntry[] {
  const pool =
    level === '중등 필수'
      ? VERIFIED_MID_VOCAB
      : level === '고등·수능 핵심'
      ? VERIFIED_CSAT_VOCAB
      : level === '비즈니스·실무'
      ? VERIFIED_BIZ_VOCAB
      : VERIFIED_OPIC_VOCAB;

  // Day 번호에 따라 정렬 순서만 순환하여 보여주며, 임의로 부사를 덧붙여 문장을 왜곡하지 않음
  const offset = ((day - 1) * 5) % pool.length;

  return Array.from({ length: pool.length }, (_, idx) => {
    const item = pool[(offset + idx) % pool.length];
    const colWords = item.collocation.split(' ');
    const soundBlockStr =
      colWords.length >= 3
        ? `${colWords.slice(0, 2).join(' ')} / ${colWords.slice(2).join(' ')}`
        : item.collocation;

    return {
      day,
      level,
      word: item.word,
      ipa: item.ipa,
      pron: item.pron,
      soundBlock: soundBlockStr,
      soundMethod: item.derivativesAndTip,
      meaning: item.meaning,
      pos: item.pos,
      posLabel: `${item.posName} (${item.pos})`,
      comp: item.comp,
      compLabel: `${item.compName} (${item.comp})`,
      collocation: item.collocation,
      collocationKo: item.collocationKo,
      exampleEn: item.exampleEn,
      exampleKo: `${item.exampleKo} — 📌 [${item.derivativesAndTip}]`,
    };
  });
}

